export function isLocale(value: unknown): value is Locale {
  return value === 'zh-CN' || value === 'en-US'
}

export function getInitialLocale(storage?: Pick<Storage, 'getItem'>, language?: string): Locale {
  const stored = storage?.getItem(localeStorageKey)
  if (isLocale(stored)) return stored
  return language?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

export function formatMessage(template: string, values: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => values[key] === undefined ? `{${key}}` : String(values[key]))
}

interface I18nContextValue {
  locale: Locale
  setLocale(locale: Locale): void
  t(key: MessageKey, values?: Record<string, string | number>): string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }): React.ReactElement {
  const [locale, setLocaleState] = useState<Locale>(() => getInitialLocale(typeof window === 'undefined' ? undefined : window.localStorage, typeof navigator === 'undefined' ? undefined : navigator.language))
  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next)
    if (typeof window !== 'undefined') window.localStorage.setItem(localeStorageKey, next)
  }, [])
  useEffect(() => { document.documentElement.lang = locale }, [locale])
  const t = useCallback((key: MessageKey, values?: Record<string, string | number>) => formatMessage(messages[locale][key] ?? messages['zh-CN'][key] ?? key, values), [locale])
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
